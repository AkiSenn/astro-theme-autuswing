import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { frontmatter } from '../src/lib/frontmatter.mjs';
import { parseDate } from '../src/lib/dates.ts';

export const contentHash = (bytes) => createHash('sha256').update(bytes).digest('hex');
const readJSON = (root, file) => JSON.parse(fs.readFileSync(path.join(root, file), 'utf8'));
const hashPattern = /^[a-f0-9]{64}$/;
const fields = [
  'version',
  'id',
  'source',
  'sequence',
  'previousSha256',
  'approvedSha256',
  'reason',
  'approvedAt',
  'commit',
].sort();

function identity(bytes, item) {
  const { data } = frontmatter(bytes.toString('utf8'));
  assert.equal(String(data.id ?? data.abbrlink ?? ''), item.id, 'Historical ID must not change');
  for (const key of ['id', 'abbrlink'])
    if (data[key] !== undefined)
      assert.equal(String(data[key]), item.id, 'Historical ID alias must not change');
  assert.equal(
    data.permalink || item.historical.path,
    item.historical.path,
    'Historical permalink must not change',
  );
  assert.equal(
    parseDate(data.date),
    item.historical.date,
    'Historical publication date must not change',
  );
  return data;
}

// The original migration manifest is never rewritten. Approval files extend its
// hash chains and are reviewed/committed in Git, not generated by a build.
export function legacyRevisionState(root, { checkCurrent = true } = {}) {
  const manifest = readJSON(root, 'migration/source-manifest.json');
  const metadata = readJSON(root, 'migration/effective-metadata.json');
  const state = new Map();
  for (const old of metadata) {
    const imported = manifest.files.find(
      (f) => f.source === 'source/' + old.source && f.target.startsWith('content/legacy/posts/'),
    );
    assert.ok(imported, `Missing original migration entry: ${old.abbrlink}`);
    assert.match(imported.sha256, hashPattern);
    assert.ok(!state.has(old.abbrlink), 'Duplicate historical ID');
    state.set(old.abbrlink, {
      id: old.abbrlink,
      source: imported.target,
      originalSha256: imported.sha256,
      approvedSha256: imported.sha256,
      sequence: 0,
      historical: old,
    });
  }
  const directory = path.join(root, 'migration/revisions');
  const names = fs.existsSync(directory)
    ? fs
        .readdirSync(directory)
        .filter((n) => n !== '.gitkeep')
        .sort()
    : [];
  const git = (...args) =>
    execFileSync('git', args, { cwd: root, windowsHide: true, stdio: ['ignore', 'pipe', 'pipe'] });
  if (names.length)
    assert.equal(
      fs.realpathSync.native(git('rev-parse', '--show-toplevel').toString().trim()),
      fs.realpathSync.native(root),
      'Approved revisions require their Git checkout and content commits',
    );
  for (const name of names) {
    assert.match(name, /^[A-Za-z0-9_-]+\.\d{6}\.json$/, `Invalid revision filename: ${name}`);
    const file = path.join(directory, name);
    assert.ok(
      fs.lstatSync(file).isFile() && !fs.lstatSync(file).isSymbolicLink(),
      `Invalid revision file: ${name}`,
    );
    const record = JSON.parse(fs.readFileSync(file, 'utf8'));
    assert.deepEqual(Object.keys(record).sort(), fields, `Invalid revision fields: ${name}`);
    assert.equal(record.version, 1, 'Unsupported revision version');
    const item = state.get(record.id);
    assert.ok(item, `Unknown historical ID: ${record.id}`);
    assert.equal(record.source, item.source, 'Revision source does not match historical ID');
    assert.equal(record.sequence, item.sequence + 1, 'Broken revision sequence');
    assert.equal(
      name,
      `${record.id}.${String(record.sequence).padStart(6, '0')}.json`,
      'Revision filename does not match record',
    );
    assert.match(record.previousSha256, hashPattern);
    assert.match(record.approvedSha256, hashPattern);
    assert.equal(record.previousSha256, item.approvedSha256, 'Broken revision hash chain');
    assert.notEqual(record.approvedSha256, record.previousSha256, 'Revision must change content');
    assert.ok(
      typeof record.reason === 'string' && record.reason.trim(),
      'Revision reason is required',
    );
    assert.ok(
      typeof record.approvedAt === 'string' && /Z$/.test(record.approvedAt),
      'Approval time must be UTC ISO',
    );
    const time = parseDate(record.approvedAt);
    assert.ok(!item.approvedAt || time >= item.approvedAt, 'Revision time runs backwards');
    assert.match(
      record.commit,
      /^[a-f0-9]{40}(?:[a-f0-9]{24})?$/,
      'Invalid approval content commit',
    );
    const committed = git('show', `${record.commit}:${item.source}`);
    assert.equal(
      contentHash(committed),
      record.approvedSha256,
      'Approval hash differs from its Git content commit',
    );
    identity(committed, item);
    Object.assign(item, {
      approvedSha256: record.approvedSha256,
      sequence: record.sequence,
      approvedAt: time,
    });
  }
  for (const item of state.values()) {
    const bytes = fs.readFileSync(path.join(root, item.source));
    item.currentSha256 = contentHash(bytes);
    const data = identity(bytes, item);
    item.updated = data.updated ? parseDate(data.updated) : item.historical.updated;
    if (checkCurrent)
      assert.equal(
        item.currentSha256,
        item.approvedSha256,
        `Unapproved historical content: ${item.source}`,
      );
  }
  return state;
}
